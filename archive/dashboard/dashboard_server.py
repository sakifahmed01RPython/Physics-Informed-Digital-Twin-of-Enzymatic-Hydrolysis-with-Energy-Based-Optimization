"""dashboard_server.py - optional LIVE SIMULATION layer for the Protein-7 console.

Replays the 15-deployment campaign over SSE. Measurements are synthesised with
the REAL fitted ODE (Alcalase arms) or the documented prior heuristic (other
enzymes), identically to src/simulate_campaign.py. Deterministic per-run seed.

    python -m src.dashboard_server            # http://127.0.0.1:8000
    DASH_PORT=8010 DASH_TICK=2000 python -m src.dashboard_server

Pure stdlib. Ctrl+C shuts down cleanly; the embedded snapshot in
reports/dashboard.html is regenerated by src/make_dashboard.py.
"""
import json
import os
import queue
import signal
import threading
import time
import urllib.parse
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import numpy as np
import pandas as pd

from src.dashboard_state import build_state, OUT, CAMPAIGN, PROCESSED, MODELS
from src.ebm_optimizer import COMPOSITION_COLS
from src.ode_model import dh_curve

HOST = os.environ.get("DASH_HOST", "127.0.0.1")
PORT = int(os.environ.get("DASH_PORT", "8000"))
TICK = int(os.environ.get("DASH_TICK", "8000"))
SEED = int(os.environ.get("DASH_SEED", "7"))
ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"

ALCALASE_SIGMA = 1.75
PRIOR_SIGMA_FLOOR = 4.0
ROUND_SIZE = 3


class SimWorld:
    """Owns the mutable state; measured rows are DEMO ONLY (never merged)."""

    def __init__(self):
        self.state = build_state()
        self.state["regime"] = "snapshot"
        self.rng = np.random.default_rng(SEED)
        self.ode_params = json.loads((MODELS / "ode_params_alcalase.json").read_text())
        self.main = pd.read_csv(PROCESSED / "main_batch_clean.csv")
        self.design = pd.read_csv(CAMPAIGN / "campaign_design.csv")
        self.comp_stats = {}
        for mat, g in self.main.groupby("RawMaterial"):
            self.comp_stats[mat] = (g[COMPOSITION_COLS].astype(float),
                                    g[COMPOSITION_COLS].astype(float).min(),
                                    g[COMPOSITION_COLS].astype(float).max())
        self.queue_idx = 0
        self.round_no = self.state["header"]["rounds_completed"]
        self.lock = threading.Lock()
        self._log_alert("SYSTEM", "info",
                        "LIVE simulation regime initialised - measurements are synthetic, "
                        "ODE-derived; physical assay required before merge")

    def now(self):
        return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    def _log_alert(self, source, level, msg):
        self.state["alerts"].insert(0, {"level": level, "source": source,
                                        "ts": self.now(), "msg": msg})
        del self.state["alerts"][12:]

    def _sample_comp(self, mat):
        if mat not in self.comp_stats:
            mat = "salmon_frames"
        base, lo, hi = self.comp_stats[mat]
        row = base.iloc[self.rng.integers(0, len(base))]
        jitter = 1.0 + self.rng.normal(0.0, 0.03, size=len(COMPOSITION_COLS))
        comp = np.clip(row.to_numpy(float) * jitter,
                       lo.to_numpy(float) * 0.9,
                       hi.to_numpy(float) * 1.1)
        return dict(zip(COMPOSITION_COLS, comp))

    def _measure(self, r):
        comp = self._sample_comp(r["RawMaterial"])
        s0 = float(r["SubstrateConc_gL"]) * comp["CrudeProtein_pct"] / 100.0
        e0 = float(r["EnzymeToSubstrateRatio"]) * s0
        dur = float(r["Duration_min"])
        if r["Enzyme"] == "Alcalase":
            dh = float(dh_curve(s0, e0, float(r["Temp_C"]), float(r["pH"]),
                                [0.0, dur], self.ode_params)[-1])
            dh += self.rng.normal(0.0, ALCALASE_SIGMA)
        else:
            rows_e = self.main[self.main["Enzyme"] == r["Enzyme"]]
            mean_dh = float(rows_e["FinalDH_pct"].mean())
            max_dh = float(rows_e["FinalDH_pct"].max())
            sigma = max(float(rows_e["FinalDH_pct"].std()) if len(rows_e) > 1 else PRIOR_SIGMA_FLOOR,
                        PRIOR_SIGMA_FLOOR)
            dh = mean_dh + 8.0 * np.log(dur / 120.0)
            cap = min(80.0, max_dh + 10.0)
            dh = float(np.clip(dh + self.rng.normal(0.0, sigma), 0.1, cap))
        return round(float(np.clip(dh, 0.1, 95.0)), 1)

    def _draft_scouts(self):
        """Open the next acquisition round: top-3 scouted points by EBM belief."""
        grid = np.asarray(self.state["landscape"]["grid"])
        order = np.argsort(grid.ravel())[::-1]
        cells = []
        for k in order[:8]:
            i, j = divmod(int(k), 10)
            cells.append((self.state["landscape"]["ph_axis"][i],
                          self.state["landscape"]["temp_axis"][j]))
        mats = list(self.comp_stats.keys())
        cand = []
        for _ in range(64):
            ph0, t0 = cells[self.rng.integers(0, len(cells))]
            cand.append({
                "pH": float(np.clip(ph0 + self.rng.normal(0, 0.25), 5.0, 9.5)),
                "Temp_C": float(np.clip(t0 + self.rng.normal(0, 2.0), 38.0, 64.0)),
                "Duration_min": float(np.exp(self.rng.uniform(np.log(60), np.log(240)))),
                "SubstrateConc_gL": float(self.rng.uniform(40.0, 65.0)),
                "Enzyme": "Alcalase",
                "RawMaterial": mats[self.rng.integers(0, len(mats))],
            })
        Xn = np.vstack([self._features(c) for c in cand])
        mu = self._expected_mu(Xn)
        best = self.state["header"]["best_observed_dh"]
        ranked = sorted(zip(cand, mu), key=lambda t: -max(0.0, t[1] - best))[:ROUND_SIZE]
        self.round_no += 1
        scouts = []
        for idx, (c, m) in enumerate(ranked):
            scouts.append({
                "id": f"S{self.round_no}R{idx + 1}",
                "arm": "scout_r%d" % self.round_no,
                "enzyme": c["Enzyme"], "RawMaterial": c["RawMaterial"],
                "ph": round(c["pH"], 2), "temp": round(c["Temp_C"], 1),
                "duration": round(c["Duration_min"], 1),
                "substrate": round(c["SubstrateConc_gL"], 1),
                "expected_dh": round(m, 1), "inspiration": f"belief {m:.1f}%",
            })
        return scouts

    def startup(self):
        from src.dashboard_state import _load_energy_net, _expected_dh
        self._model, mean, std = _load_energy_net()
        self._stats = (mean, std)
        self._expected_mu = lambda Xn: _expected_dh(Xn, self._model, mean, std)
        self._comp_last = {}
        for mat, (base, _, _) in self.comp_stats.items():
            self._comp_last[mat] = {c: float(base[c].median())
                                    for c in COMPOSITION_COLS}

    def _features(self, r):
        from src.ebm_optimizer import PROCESS_COLS, ENZYMES, ENZYME_INDEX
        mean, std = self._stats
        comp = self._comp_last[r["RawMaterial"]]
        num = np.asarray([float(r[c]) for c in PROCESS_COLS] +
                         [comp[c] for c in COMPOSITION_COLS])
        oh = np.zeros(len(ENZYMES))
        oh[ENZYME_INDEX[r["Enzyme"]]] = 1.0
        return ((np.concatenate([num, oh]) - mean) / std).reshape(1, -1)

    def tick(self):
        with self.lock:
            h = self.state["header"]
            roster = self.state["roster"]
            if self.queue_idx >= len(roster):
                scouts = self._draft_scouts()
                for sc in scouts:
                    roster.append({
                        "id": sc["id"], "arm": sc["arm"], "enzyme": sc["enzyme"],
                        "ph": sc["ph"], "temp": sc["temp"],
                        "duration": sc["duration"], "substrate": sc["substrate"],
                        "status": "pending", "measured_dh": None,
                        "expected_dh": sc["expected_dh"]})
                    self.state["landscape"]["nodes"].append({
                        "id": sc["id"], "type": "deployment",
                        "ph": sc["ph"], "temp": sc["temp"], "v": sc["expected_dh"],
                        "arm": sc["arm"], "enzyme": sc["enzyme"],
                        "status": "pending"})
                h["deployments_total"] = len(roster)
                self._log_alert("ACQUISITION", "info",
                                f"Round {self.round_no} opened - {len(scouts)} scouts "
                                f"deployed from top-belief cells")
            entry = roster[self.queue_idx]
            self.queue_idx += 1
            entry["status"] = "running"
            for n in self.state["landscape"]["nodes"]:
                if n["id"] == entry["id"]:
                    n["status"] = "running"
            payload = self._snapshot()
            self._write_file(payload)
            return payload

    def complete_next(self):
        with self.lock:
            h = self.state["header"]
            roster = self.state["roster"]
            idx = self.queue_idx - 1
            if idx < 0 or idx >= len(roster):
                return None
            entry = roster[idx]
            if entry["status"] != "running":
                return None
            design_row = self.design[self.design["BatchID"] == entry["id"]]
            if len(design_row):
                r = design_row.iloc[0]
                dh = self._measure(r)
                basis = "physics" if r["Enzyme"] == "Alcalase" else "prior_low_conf"
            else:
                dh = float(entry["expected_dh"]) + self.rng.normal(0, ALCALASE_SIGMA)
                basis = "scout"
            entry["status"] = "complete"
            entry["measured_dh"] = dh
            for n in self.state["landscape"]["nodes"]:
                if n["id"] == entry["id"]:
                    n["status"] = "complete"
            h["deployments_done"] += 1
            if dh > h["best_observed_dh"]:
                h["best_observed_dh"] = dh
                self._log_alert("RECORD", "info",
                                f"{entry['id']} measured DH {dh:.1f}% - new best observed")
            else:
                self._log_alert("CAMPAIGN", "info",
                                f"{entry['id']} measured {dh:.1f}% "
                                f"({basis}) - logged, kept under audit")
            payload = self._snapshot()
            self._write_file(payload)
            return payload

    def _snapshot(self):
        s = dict(self.state)
        s["regime"] = "live"
        return s

    def _write_file(self, payload):
        p = dict(payload)
        p["regime"] = "snapshot"
        OUT.write_text(json.dumps(p, indent=1, allow_nan=False), encoding="utf-8")


class Handler(BaseHTTPRequestHandler):
    world = None
    subscribers = []
    lock = threading.Lock()

    def log_message(self, *a):
        pass

    def _send(self, code, body, ctype):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        w = Handler.world
        path = urllib.parse.urlsplit(self.path).path
        if path in ("/api/state", "/api/state/"):
            self._send(200, json.dumps(w._snapshot()).encode(),
                       "application/json")
        elif path == "/api/stream":
            self._send_sse()
        elif path in ("/", "/index.html"):
            self.send_response(302)
            self.send_header("Location", "/dashboard.html")
            self.end_headers()
        elif path.rstrip("/") == "/dashboard.html":
            body = (REPORTS / "dashboard.html").read_bytes()
            self._send(200, body, "text/html; charset=utf-8")
        else:
            self.send_error(404)

    def _send_sse(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Connection", "keep-alive")
        self.end_headers()
        q = queue.Queue()
        with Handler.lock:
            Handler.subscribers.append(q)
        try:
            self.wfile.write(b"retry: 3000\n\n")
            self.wfile.flush()
            while True:
                try:
                    payload = q.get(timeout=15)
                    data = json.dumps(payload)
                    self.wfile.write(b"data: " + data.encode() + b"\n\n")
                    self.wfile.flush()
                except queue.Empty:
                    self.wfile.write(b":hb\n\n")
                    self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError, OSError):
            pass
        finally:
            with Handler.lock:
                if q in Handler.subscribers:
                    Handler.subscribers.remove(q)

    @classmethod
    def broadcast(cls, payload):
        with cls.lock:
            subs = list(cls.subscribers)
        for q in subs:
            q.put(payload)


class SimRunner(threading.Thread):
    def __init__(self, world):
        super().__init__(daemon=True)
        self.world = world
        self.stop = threading.Event()
        self._tick_sync = time.monotonic()

    def run(self):
        while not self.stop.is_set():
            self.world.tick()
            time.sleep(TICK / 1000.0)
            payload = self.world.complete_next()
            if payload:
                Handler.broadcast(payload)


def main():
    world = SimWorld()
    world.startup()
    Handler.world = world
    Handler.subscribers = []
    server = ThreadingHTTPServer((HOST, PORT), Handler)
    server.daemon_threads = True

    def shutdown(sig, frame):
        print("\n[dashboard_server] shutting down cleanly...")
        threading.Thread(target=server.shutdown, daemon=True).start()

    signal.signal(signal.SIGINT, shutdown)
    signal.signal(signal.SIGTERM, shutdown)

    runner = SimRunner(world)
    runner.start()
    print(f"[dashboard_server] LIVE SIMULATION REGIME  ->  http://{HOST}:{PORT}/dashboard.html")
    print(f"  tick={TICK}ms seed={SEED} roster={world.state['header']['deployments_total']} "
          f"rounds_start={world.round_no}")
    print("  state.json refreshed per tick (snapshot regime); Ctrl+C to stop")
    try:
        server.serve_forever(poll_interval=0.5)
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
        runner.stop.set()
        print("[dashboard_server] stopped.")


if __name__ == "__main__":
    main()